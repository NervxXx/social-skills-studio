# Короткий формирующий фидбек по оценкам (русский)
def get_formative_feedback(
    empathy: int,
    clarity: int,
    emotional_control: int,
    assertiveness: int,
    focus_skill: str = "all",
) -> str:
    """
    Одна короткая фраза после хода: похвала или совет.
    Приоритет у навыка, на котором фокус, и у самых низких оценок.
    """
    scores = [
        ("empathy", empathy, "Эмпатия"),
        ("clarity", clarity, "Ясность"),
        ("control", emotional_control, "Самообладание"),
        ("assertiveness", assertiveness, "Уверенность"),
    ]
    # Сортируем по оценке (сначала самые низкие), учитываем focus
    def key(item):
        name, val, _ = item
        penalty = 0 if name == focus_skill or focus_skill == "all" else 15
        return val + penalty

    scores_sorted = sorted(scores, key=key)

    # Сильная сторона — похвала
    strong = next((s for s in scores_sorted if s[1] >= 75), None)
    if strong and strong[1] >= 80:
        name, val, label = strong
        if name == "empathy":
            return "Отлично: вы хорошо отразили чувства собеседника."
        if name == "clarity":
            return "Хорошо: вы сказали конкретно и по делу."
        if name == "control":
            return "Хорошо: вы сохранили спокойствие."
        if name == "assertiveness":
            return "Хорошо: вы чётко обозначили свою позицию."

    # Слабое место — совет
    weak = scores_sorted[0]
    name, val, _ = weak
    if val >= 60:
        return "Продолжайте в том же духе."
    if name == "empathy":
        if val < 40:
            return "Совет: назовите чувство собеседника перед советом или вопросом."
        return "Подсказка: перефразируйте сказанное, чтобы показать, что вы слушаете."
    if name == "clarity":
        if val < 40:
            return "Совет: опишите конкретную ситуацию и одну чёткую просьбу."
        return "Подсказка: избегайте «всегда»/«никогда» — приведите пример."
    if name == "control":
        if val < 40:
            return "Совет: сделайте паузу и ответьте спокойно, не повышая тон."
        return "Подсказка: можно начать с «Я слышу тебя» и потом сказать своё."
    if name == "assertiveness":
        if val < 40:
            return "Совет: сформулируйте прямо, чего вы хотите или в чём граница."
        return "Подсказка: используйте «мне нужно», «для меня важно»."
    return "Продолжайте практиковаться."


def get_turn_hint(
    focus_skill: str,
    turn_index: int,
    language: str = "ru",
) -> str:
    """
    Подсказка для следующего хода по фокус-навыку и номеру хода.
    """
    skill_key = focus_skill if focus_skill in HINTS_BY_SKILL else "all"
    hints = HINTS_BY_SKILL[skill_key]
    index = turn_index % len(hints)
    return hints[index]
